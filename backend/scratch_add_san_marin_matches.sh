#!/bin/bash
set -e
API=http://localhost:8081/api/matches
COMP=65

post() {
  local round="$1" date="$2" time="$3" t1="$4" t2="$5"
  curl -s -o /tmp/resp.json -w "%{http_code}" -X POST "$API" \
    -H "Content-Type: application/json" \
    -d "{\"competitionId\":$COMP,\"roundLabel\":\"$round\",\"date\":\"$date\",\"time\":\"$time\",\"team1Id\":$t1,\"team2Id\":$t2}" > /tmp/code.txt
  code=$(cat /tmp/code.txt)
  if [ "$code" != "201" ]; then
    echo "FAILED ($code) $round $date $t1 vs $t2:"
    cat /tmp/resp.json
    echo
  else
    echo "OK $round $date $t1 vs $t2"
  fi
}

