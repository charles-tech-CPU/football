SELECT s.code AS competition,
       s.equipe1 || ' - ' || s.equipe2 AS match,
       m.date AS date_serveur, m.time AS heure_serveur,
       s.date_source, s.heure_source,
       CASE
         WHEN m.id IS NULL AND r.id IS NOT NULL THEN 'domicile / exterieur inverses sur le serveur'
         WHEN m.id IS NULL THEN 'match absent du serveur'
         WHEN m.date IS DISTINCT FROM s.date_source THEN 'date differente'
         ELSE 'heure differente'
       END AS ecart
FROM source s
JOIN competition c ON c.code = s.code AND c.season = 2027
JOIN team t1 ON t1.name = s.equipe1
JOIN team t2 ON t2.name = s.equipe2
LEFT JOIN match m ON m.competition_id = c.id AND m.team1_id = t1.id AND m.team2_id = t2.id
     AND (m.date IS NULL OR m.date BETWEEN s.date_source - 10 AND s.date_source + 10)
LEFT JOIN match r ON m.id IS NULL AND r.competition_id = c.id AND r.team1_id = t2.id AND r.team2_id = t1.id
     AND r.date BETWEEN s.date_source - 10 AND s.date_source + 10
WHERE m.id IS NULL
   OR m.date IS DISTINCT FROM s.date_source
   OR (s.heure_source IS NOT NULL AND m.time IS DISTINCT FROM s.heure_source)
ORDER BY s.date_source, s.heure_source, competition, match;
